"""Generates atom-console: the atom plus a synthetic hexadecimal memory dump typed over its orbits.
Busy types in royal blue; Attention types in gold at twice the speed. No real memory is read.
Typing runs without pauses, also over the loop restart; now and then a wide memory-dump burst
scrolls over the atom instead (../dump_burst.py).

XAML has no random numbers, so the gibberish, positions and typing rhythm are baked in here with a
fixed seed. Re-run after editing: py -3 -I make_skin.py  (the Adjutant hot-reloads the result).
"""
import random
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))   # -I leaves the script folder off sys.path
import console_common  # noqa: E402
import dump_burst  # noqa: E402
from console_common import ts  # noqa: E402
BASE = HERE.parent / "atom" / "skin.xaml"
OUT = HERE / "skin.xaml"

SEED = 7
BLOCKS = 9                      # notepad blocks per cycle, rotating through the text slots (a multiple of 3)
SLOTS = "ABC"                   # three slots, so typing never waits for an old block to fade
LINES = (2, 6)                  # inclusive randomized lines per block
BYTES_PER_LINE = 3              # compact offsets plus aligned byte pairs
CHAR_SECONDS = (0.035, 0.085)   # delay per typed character (Busy speed)
HOLD = 1.0                      # finished block stays this long, cursor blinking
FADE = 0.5
BLINK = 0.25
FONT_SIZE = 12
CHAR_WIDTH = 6.0                # IosevkaTerm advance at FONT_SIZE (0.5 em), for the overlap check
LINE_HEIGHT = 15                # IosevkaTerm natural line height at FONT_SIZE
CURSOR = "█"
# Upright spots over the orbit arms; compact address/byte columns fit up to six lines.
SPOTS = [(12, 24), (112, 34), (16, 150), (106, 166), (64, 92), (118, 98), (8, 86), (70, 6)]
JITTER = 12                     # px each way, per placement
INK = {"Busy": "#FF8FB4FF", "Attention": "#FFFFE7A8"}
SPEED = {"Busy": 1.0, "Attention": 2.0}



def gibberish_line(rng, offset):
    octets = " ".join("{:02X}".format(rng.randrange(256)) for _ in range(BYTES_PER_LINE))
    return "{:04X} {}".format(offset, octets)


def build_blocks(rng):
    blocks = []
    # Include every supported height, then randomize the cycle.
    line_counts = list(range(LINES[0], LINES[1] + 1))
    line_counts += [rng.randint(*LINES) for _ in range(BLOCKS - len(line_counts))]
    rng.shuffle(line_counts)
    offset = 0
    for i in range(BLOCKS):
        lines = []
        for _ in range(line_counts[i]):
            lines.append(gibberish_line(rng, offset))
            offset += BYTES_PER_LINE
        steps = []                                  # (seconds after block start, visible text)
        t, typed = 0.0, ""
        for n, line in enumerate(lines):
            if n:
                typed += "\n"
            for ch in line:
                t += rng.uniform(*CHAR_SECONDS)
                typed += ch
                steps.append((t, typed + CURSOR))
        width = (max(len(line) for line in lines) + 1) * CHAR_WIDTH
        blocks.append({"steps": steps, "typed_end": t, "text": typed, "size": (width, len(lines) * LINE_HEIGHT)})
    return blocks


def candidates(block, rng):
    """Every spot, jittered, so placements vary from loop to loop; kept inside the 256 canvas."""
    w, h = block["size"]
    return [(min(max(2, x + rng.uniform(-JITTER, JITTER)), 254 - w),
             min(max(2, y + rng.uniform(-JITTER, JITTER)), 254 - h)) for x, y in SPOTS]


def main():
    rng = random.Random(SEED)
    blocks = build_blocks(rng)
    spots = console_common.place(rng, blocks, candidates, lambda b: b["size"], SLOTS)
    dump_rng = random.Random(SEED + dump_burst.SEED_OFFSET)
    burst_times, burst_loop = dump_burst.schedule(dump_rng)
    xaml = BASE.read_text(encoding="utf-8")

    xaml = xaml.replace(
        "  Default Adjutant skin: a glowing atom (nucleus + three electrons on tilting orbit planes).\n"
        "  Placeholder art by Claude; see ../../SKIN-CONTRACT.md for the rules a skin must follow.",
        "  atom-console: the atom skin plus a synthetic hexadecimal dump typed over the orbits\n"
        "  while agents are Busy (royal blue) or need Attention (pulsing gold, twice as fast).\n"
        "  GENERATED by make_skin.py from ../atom/skin.xaml: edit that script, not this file.")

    for state in ("Busy", "Attention"):
        loop, cycle = console_common.typing_xml(blocks, spots, SLOTS, SPEED[state], HOLD, FADE, BLINK, CURSOR)
        bursts = dump_burst.timelines(burst_times, burst_loop, SPEED[state], ts)
        anchor = '<Storyboard x:Key="{}">'.format(state)
        assert anchor in xaml, anchor
        head, tail = xaml.split(anchor, 1)
        body, rest = tail.split("</Storyboard>", 1)
        ink = "\n".join(
            '      <ColorAnimation Storyboard.TargetName="Ink{}" Storyboard.TargetProperty="Color" '
            'To="{}" Duration="0:0:0.2"/>'.format(slot, INK[state]) for slot in SLOTS
        ) + "\n" + dump_burst.ink_animation(INK[state])
        xaml = head + anchor + body.rstrip() + "\n" + ink + loop + bursts + "\n    </Storyboard>" + rest

    notes = "\n".join(
        '      <TextBlock x:Name="Note{0}" Opacity="0" FontFamily="{3}" FontWeight="Medium" FontSize="{1}" IsHitTestVisible="False">\n'
        '      <TextBlock.Foreground><SolidColorBrush x:Name="Ink{0}" Color="{2}"/></TextBlock.Foreground>\n'
        '      </TextBlock>'.format(slot, FONT_SIZE, INK["Busy"], console_common.FONT) for slot in SLOTS)
    end = "  </Canvas>\n</Grid>"
    assert xaml.rstrip().endswith(end)
    xaml = (xaml.rstrip()[: -len(end)] + "\n    <!-- Notepad text; empty and invisible outside Busy and Attention. -->\n"
            + '    <Canvas x:Name="TypingLayer" IsHitTestVisible="False">\n' + notes + "\n    </Canvas>\n"
            + dump_burst.element(dump_rng, INK["Busy"]) + "\n" + end + "\n")
    # ASCII with character references: XamlReader.Parse rejected the raw UTF-8 cursor glyph.
    OUT.write_text(xaml, encoding="ascii", errors="xmlcharrefreplace", newline="\n")
    print("wrote {} ({} KB, {} blocks)".format(OUT.name, OUT.stat().st_size // 1024, len(blocks)))


if __name__ == "__main__":
    main()
